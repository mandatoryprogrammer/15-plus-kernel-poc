func probeModuleSupervisorCommand(c *cache, args []string) error {
	var modules []string
	var contractPath, destination string
	seen := map[string]bool{}
	for index := 0; index < len(args); index++ {
		if index+1 >= len(args) {
			return fmt.Errorf("%s needs a value", args[index])
		}
		option, value := args[index], args[index+1]
		index++
		switch option {
		case "--module":
			if !probeModuleRegistry[value] {
				return fmt.Errorf("unknown probe module %q", value)
			}
			if seen[value] {
				return fmt.Errorf("duplicate probe module %q", value)
			}
			seen[value] = true
			modules = append(modules, value)
		case "--contract":
			if contractPath != "" {
				return errors.New("--contract may appear once")
			}
			contractPath = value
		case "--dest":
			if destination != "" {
				return errors.New("--dest may appear once")
			}
			destination = value
		default:
			return fmt.Errorf("unknown modular supervisor option %q", option)
		}
	}
	if len(modules) == 0 || contractPath == "" {
		return errors.New("modular supervisor requires --module NAME and --contract target-image.json")
	}
	sort.Strings(modules)
	contract, contractPath, contractSHA, err := loadTargetImageContract(contractPath)
	if err != nil {
		return err
	}
	if destination == "" {
		destination = filepath.Join(c.root, "private", "probe-target-control.h")
	} else if destination, err = filepath.Abs(destination); err != nil {
		return err
	}
	source, err := renderTargetControlModule(contract, modules)
	if err != nil {
		return err
	}
	if err = writeProbeFile(destination, source, 0o600); err != nil {
		return err
	}
	report := probeModuleReport{Schema: "15-plus-kernel-poc.probe-module.v1", Modules: modules, Contract: contractPath, ContractSHA256: contractSHA, Source: destination, SHA256: digest(source)}
	if err = writeProbeJSON(c, "probe-module-latest.json", report); err != nil {
		return err
	}
	fmt.Fprintf(c.out, "Generated target-control module modules=%s contract_sha256=%s sha256=%s source=%s\n", strings.Join(modules, ","), contractSHA, digest(source), destination)
	return nil
}
